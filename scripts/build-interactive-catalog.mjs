import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../data/visualization-components/catalog.v1.json", import.meta.url);
const target = new URL("../packages/contracts/src/artifacts/interactive-catalog.mjs", import.meta.url);
const catalog = JSON.parse(readFileSync(source, "utf8"));
const entries = catalog.components.filter((entry) => entry.implementation.status === "implemented").map((entry) => ({
  componentId: entry.componentId,
  version: entry.version,
  name: entry.name["zh-CN"],
  description: entry.catalogDescription["zh-CN"],
  names: entry.name,
  descriptions: entry.catalogDescription,
  disciplines: entry.disciplineTags,
  capabilities: entry.capabilityTags,
  purpose: entry.teachingPurpose,
  examples: entry.examplePrompts,
  exclusions: entry.fallbackConditions,
  search: entry.search ?? {},
}));
const hash = createHash("sha256").update(JSON.stringify(entries)).digest("hex");
const versionsTarget = new URL("../packages/contracts/src/artifacts/interactive-versions.mjs", import.meta.url);
const versionsOutput = `// Generated by scripts/build-interactive-catalog.mjs.\nexport const INTERACTIVE_COMPONENT_VERSIONS = ${JSON.stringify(Object.fromEntries(entries.map((entry) => [entry.componentId, entry.version])), null, 2)};\n`;
const output = `// Generated by scripts/build-interactive-catalog.mjs. Edit the versioned JSON catalog.\nexport const INTERACTIVE_CATALOG_HASH = ${JSON.stringify(hash)};\nexport const INTERACTIVE_COMPONENT_CATALOG = ${JSON.stringify(entries, null, 2)};\n\nexport const INTERACTIVE_COMPONENT_IDS = INTERACTIVE_COMPONENT_CATALOG.map((entry) => entry.componentId);\n\nexport function formatInteractiveCatalogLines() {\n  return INTERACTIVE_COMPONENT_CATALOG.map((entry) => \`- \${entry.componentId}(\${entry.name}):\${entry.description}\`).join("\\n");\n}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output || readFileSync(versionsTarget, "utf8") !== versionsOutput) {
    console.error("[interactive-catalog] stale generated catalog; run pnpm catalog:build");
    process.exitCode = 1;
  } else console.log(`[interactive-catalog] ${entries.length} entries, hash=${hash}`);
} else {
  writeFileSync(target, output);
  writeFileSync(versionsTarget, versionsOutput);
  console.log(`[interactive-catalog] generated ${entries.length} entries: ${fileURLToPath(target)}`);
}
