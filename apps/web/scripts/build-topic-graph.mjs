#!/usr/bin/env node
// Collapse the concept-level prerequisite graph into a topic-level DAG artifact.
// Source of truth: temple/<graphId>.json (committed).
// Output: src/lib/knowledge-graph/data/topic-graph.<graphId>.json
//
// The topic DAG powers prerequisite/remediation lookups. Curriculum progression
// follows the immediate next default_order topic in topic-graph.ts.
//
// Usage: node build-topic-graph.mjs [<graphId> | all]

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { REPO_ROOT, graphPath, listGraphIds, DEFAULT_GRAPH_ID } from "./kg-db-common.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(__dirname, "../src/lib/knowledge-graph/data");

function buildOne(graphId) {
  const source = graphPath(graphId);
  const graph = JSON.parse(readFileSync(source, "utf8"));
  const out = resolve(OUT_DIR, `topic-graph.${graphId}.json`);

  const topics = new Map();
  const conceptTopic = new Map();

  for (const node of graph.nodes) {
    if (node.kind === "topic") {
      topics.set(node.id, {
        topicId: node.id,
        name: node.name,
        defaultOrder: node.default_order,
        conceptIds: [],
        successors: [], // {topicId, hard}
        prereqTopics: [], // upstream topic ids (any strength)
      });
    }
  }
  for (const node of graph.nodes) {
    if (node.kind === "concept") {
      conceptTopic.set(node.id, node.topic);
      topics.get(node.topic).conceptIds.push({ conceptId: node.id, name: node.name, defaultOrder: node.default_order });
    }
  }

  // Collapse concept prereq edges to topic edges (drop intra-topic + dedupe).
  const succ = new Map(); // ft -> Map(tt -> hard?)
  const pred = new Map(); // tt -> Set(ft)
  for (const e of graph.edges) {
    if (e.type !== "prereq") continue;
    const ft = conceptTopic.get(e.from);
    const tt = conceptTopic.get(e.to);
    if (!ft || !tt || ft === tt) continue;
    if (!succ.has(ft)) succ.set(ft, new Map());
    const m = succ.get(ft);
    m.set(tt, (m.get(tt) || false) || e.strength === "hard");
    if (!pred.has(tt)) pred.set(tt, new Set());
    pred.get(tt).add(ft);
  }

  for (const [tid, t] of topics) {
    t.conceptIds.sort((a, b) => a.defaultOrder - b.defaultOrder);
    const m = succ.get(tid) || new Map();
    t.successors = [...m.entries()]
      .map(([topicId, hard]) => ({ topicId, hard }))
      .sort((a, b) => topics.get(a.topicId).defaultOrder - topics.get(b.topicId).defaultOrder);
    t.prereqTopics = [...(pred.get(tid) || new Set())].sort(
      (a, b) => topics.get(a).defaultOrder - topics.get(b).defaultOrder,
    );
    t.isRoot = t.prereqTopics.length === 0;
  }

  const ordered = [...topics.values()].sort((a, b) => a.defaultOrder - b.defaultOrder);

  const artifact = {
    graphId,
    subject: graph.subject,
    generatedFrom: `temple/${graphId}.json`,
    generatedAt: new Date().toISOString().slice(0, 10),
    note: "Topic-level DAG collapsed from concept prereq edges. successors are prerequisite relations; curriculum progression follows the immediate next defaultOrder topic.",
    topics: ordered,
  };

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(out, JSON.stringify(artifact, null, 2) + "\n");

  const topicEdges = [...succ.values()].reduce((n, m) => n + m.size, 0);
  process.stdout.write(
    `[build-topic-graph] ${graphId}: ${ordered.length} topics, ${topicEdges} topic edges -> ${relative(REPO_ROOT, out)}\n`,
  );
}

// Regenerate the static barrel (src/lib/knowledge-graph/data/topic-graphs.generated.ts)
// that imports every topic-graph.<id>.json so consumers never hand-register graphs.
function writeBarrel() {
  const ids = listGraphIds(); // source of truth = temple/*.json
  const importLines = ids.map((id, i) => `import g${i} from "./topic-graph.${id}.json";`);
  const mapLines = ids.map((id, i) => `  ${JSON.stringify(id)}: g${i} as unknown as TopicGraph,`);
  const body = `// AUTO-GENERATED by scripts/build-topic-graph.mjs. Do not edit by hand.
// Run \`pnpm build:topic-graph all\` after adding/removing a temple/*.json graph.
import type { TopicGraph } from "../topic-graph";

${importLines.join("\n")}

export const DEFAULT_TOPIC_GRAPH_ID = ${JSON.stringify(DEFAULT_GRAPH_ID)};

export const TOPIC_GRAPHS: Record<string, TopicGraph> = {
${mapLines.join("\n")}
};
`;
  const out = resolve(OUT_DIR, "topic-graphs.generated.ts");
  writeFileSync(out, body);
  process.stdout.write(`[build-topic-graph] barrel -> ${relative(REPO_ROOT, out)} (${ids.length} graphs)\n`);
}

const arg = process.argv[2] || DEFAULT_GRAPH_ID;
const ids = arg === "all" ? listGraphIds() : [arg];
for (const id of ids) buildOne(id);
writeBarrel();
